def merge_lang(code, entries):
    path = os.path.join(ASSETS, 'lang', code + '.json')
    with open(path, encoding='utf-8') as f:
        data = json.load(f)
    data.update(entries)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(json.dumps(data, indent=2, ensure_ascii=False))


def write_json(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(json.dumps(obj, indent=2))


def scroll_entry(sid, weight):
    el = SPELLS[sid][0]
    return {
        'type': 'minecraft:item',
        'name': 'mistech:spell_scroll',
        'weight': weight,
        'functions': [{
            'function': 'minecraft:set_components',
            'components': {
                'mistech:spell_id': sid,
                'minecraft:custom_model_data': {'colors': [COLORS[el]]},
            },
        }],
    }


def loot_table(tiers, empty_weight, exclusive_weight):
    entries = []
    for sid, (el, tier, wo, *_rest) in SPELLS.items():
        if tier in tiers:
            entries.append(scroll_entry(sid, exclusive_weight if wo else 10))
    entries.append({'type': 'minecraft:empty', 'weight': empty_weight})
    return {'type': 'minecraft:chest', 'pools': [{'rolls': 1, 'bonus_rolls': 0, 'entries': entries}]}


